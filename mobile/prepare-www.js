// Copies the web app into www/ for the Android build and points it at the cloud server.
const fs = require('fs');
const path = require('path');

const src = path.join(__dirname, '..', 'daybook', 'static');
const out = path.join(__dirname, 'www');
const { apiBase } = JSON.parse(fs.readFileSync(path.join(__dirname, 'app.config.json'), 'utf8'));

if (!/^https:\/\/[^/]+$/.test(apiBase) || apiBase.includes('REPLACE')) {
  console.error(`app.config.json: apiBase must be the server's https address (got "${apiBase}")`);
  process.exit(1);
}

fs.rmSync(out, { recursive: true, force: true });
fs.cpSync(src, out, { recursive: true });
fs.writeFileSync(path.join(out, 'config.js'),
  `// Generated by prepare-www.js\nwindow.DAYBOOK_API_BASE = ${JSON.stringify(apiBase)};\n`);
console.log(`www/ ready, API -> ${apiBase}`);
